import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const owner='11111111-1111-4111-8111-111111111111',alice='22222222-2222-4222-8222-222222222222',bob='33333333-3333-4333-8333-333333333333';
const dir=new URL('../supabase/migrations/',import.meta.url),name=(await readdir(dir)).find(n=>n.endsWith('_room_guestbook.sql'));
const migration=await readFile(new URL(name,dir),'utf8');
test('guestbook enforces author edits, owner moderation, pause, recovery and pagination',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon; create role authenticated; create schema auth;
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   create table auth.identities(user_id uuid,provider text,provider_id text,identity_data jsonb);
   grant usage on schema public,auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;
   create schema room_private; revoke all on schema room_private from public,anon,authenticated;
   create function public.room_can_edit() returns boolean language sql stable security definer set search_path='' as $$ select coalesce(auth.uid()='${owner}'::uuid,false) $$;
   insert into auth.identities values('${owner}','github','owner','{"user_name":"owner"}'),('${alice}','github','alice','{"user_name":"alice"}'),('${bob}','github','bob','{"user_name":"bob","role":"owner"}');`);
  await db.exec(migration);
  const role=async(uid)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid||'']);await db.exec('set role '+(uid?'authenticated':'anon'));};
  const list=async(args=[])=>(await db.query('select public.room_guestbook_list($1,$2,$3,$4) as x',[args[0]||null,args[1]||null,args[2]||24,args[3]||false])).rows[0].x;
  const save=async(body,color='paper',id=null)=>(await db.query('select public.room_guestbook_save($1,$2,$3) as x',[body,color,id])).rows[0].x;
  await role(null);assert.equal((await list()).enabled,true);assert.equal((await list()).owner,false);
  await assert.rejects(save('anon'),/permission denied/);
  await assert.rejects(db.query('select * from room_private.guestbook_notes'),/permission denied/);
  await role(alice);const note=await save('A quiet room.','sage');
  assert.equal((await list()).notes[0].mine,true);assert.equal((await list()).notes[0].authorName,'alice');
  assert.equal('author_id' in (await list()).notes[0],false);
  await save('A quiet room, edited.','blush',note.id);assert.equal((await list()).notes[0].body,'A quiet room, edited.');
  await assert.rejects(save('too soon'),/一分钟/);
  await assert.rejects(save('x'.repeat(281),'paper',note.id),/280/);
  await assert.rejects(save('bad','red',note.id),/280/);
  await role(bob);assert.equal((await list()).notes[0].mine,false);
  await assert.rejects(save('attack','paper',note.id),/只能修改自己/);
  await assert.rejects(db.query('select public.room_guestbook_moderate($1)',[note.id]),/只有站主/);
  await assert.rejects(db.query('select public.room_guestbook_configure(false)'),/只有站主/);
  await assert.rejects(db.query('update room_private.guestbook_notes set author_id=$1',[bob]),/permission denied/);
  await role(owner);await assert.rejects(save('rewrite visitor','paper',note.id),/只能修改自己/);
  await db.query('select public.room_guestbook_configure(false)');
  await role(alice);assert.equal((await list()).notes[0].canEdit,false);await assert.rejects(save('paused','paper',note.id),/收起了笔/);
  await role(owner);await db.query('select public.room_guestbook_moderate($1)',[note.id]);
  assert.equal((await list([null,null,24,true])).notes.length,1);
  await role(null);assert.equal((await list([null,null,24,true])).notes.length,0);
  await role(owner);await db.query('select public.room_guestbook_moderate($1,true)',[note.id]);await db.query('select public.room_guestbook_configure(true)');
  await role(null);assert.equal((await list()).notes.length,1);assert.equal((await list()).notes[0].canEdit,false);
  await db.exec('reset role');
  await db.query("insert into room_private.guestbook_notes(author_id,author_name,body,created_at) select $1,'alice','Page '||i,now()-i*interval '1 minute' from generate_series(1,30) i",[alice]);
  await role(null);const first=await list([null,null,20]),second=await list([first.nextCursor.before,first.nextCursor.id,20]);
  assert.equal(first.hasMore,true);assert.equal(second.hasMore,false);assert.equal(first.notes.length+second.notes.length,31);
  assert.equal(new Set([...first.notes,...second.notes].map(n=>n.id)).size,31);
 }finally{await db.close();}
});
